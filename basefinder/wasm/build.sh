#!/usr/bin/env bash
# Builds cubiomes + bridge.c into WebAssembly and writes ../cubiomes-wasm.js
# (the .wasm as base64, so the page also works when opened straight from disk).
#
# Needs: clang with the wasm32 target, wasm-ld, git, base64.
set -euo pipefail

CUBIOMES_REPO="https://github.com/Cubitect/cubiomes.git"
CUBIOMES_COMMIT="e61f90580cbdd883214a8054670dacae655e59c0" # 2024-11-10, has 1.21.4+ (pale garden)

HERE="$(cd "$(dirname "$0")" && pwd)"
BUILD="$HERE/build"
SRC="$BUILD/cubiomes"
mkdir -p "$BUILD"

if [ ! -d "$SRC/.git" ]; then
    git clone --quiet "$CUBIOMES_REPO" "$SRC"
fi
git -C "$SRC" fetch --quiet origin "$CUBIOMES_COMMIT" 2>/dev/null || true
git -C "$SRC" checkout --quiet "$CUBIOMES_COMMIT"

CLANG="${CLANG:-clang}"
"$CLANG" --target=wasm32 -O3 -std=c11 -nostdlib \
    -mbulk-memory -mnontrapping-fptoint -msign-ext -mmutable-globals \
    -isystem "$HERE/libc/include" -I "$SRC" \
    -Wno-unused-function \
    -Wl,--no-entry -Wl,--strip-all -Wl,--gc-sections \
    -Wl,-z,stack-size=1048576 \
    -o "$BUILD/cubiomes.wasm" \
    "$HERE/bridge.c" "$HERE/libc/libc.c" \
    "$SRC/generator.c" "$SRC/biomenoise.c" "$SRC/layers.c" "$SRC/noise.c" "$SRC/biomes.c"

{
    echo "// Generated by wasm/build.sh from cubiomes $CUBIOMES_COMMIT (MIT licence). Do not edit."
    printf 'self.CUBIOMES_WASM_B64 = "'
    base64 -w0 "$BUILD/cubiomes.wasm"
    echo '";'
} > "$HERE/../cubiomes-wasm.js"

echo "wrote $(wc -c < "$BUILD/cubiomes.wasm") byte wasm -> cubiomes-wasm.js"
